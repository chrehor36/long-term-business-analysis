s=[]
for y in range(2012,2026):
    e=NI[y]+TAX[y]+INT[y]
    cap=(DEBT[y]+EQ[y]+DEBT[y-1]+EQ[y-1])/2
    roc=e/cap; roe=NI[y]/((EQ[y]+EQ[y-1])/2)
